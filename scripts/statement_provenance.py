#!/usr/bin/env python3
"""
Statement provenance across the four Delphi rounds.

Round 2 -> Round 3 is recorded in data/delphi/provenance/r2_r3_mapping.csv, one row per
line of the revision-mapping table (tab:revision_mapping): the Round 2 position or
positions, the Round 3 positions, the Round 3 section, the type of change, and a
summary. The summary is LaTeX source, as the table prints it. This script writes
tables/revision_mapping.tex from that file, so the table has one source.

Round 3 -> Round 4 comes from R4_TO_R3 in r4_statements.py.

Round 1 -> Round 2 follows the Round 1 feedback summaries and the Round 1 to
Round 2 mapping document: data/delphi/provenance/r1_r2_documented.csv gives, for each of
the 26 Round 2 statements, its Round 1 source or sources (empty where it was
written new), the relation and the basis. Round 1 statement 3 has no Round 2
successor. The earlier proposal by word overlap, r1_r2_proposal.csv, is kept as
it was for the record and no longer written.

The GPT-5 first draft -> Round 1 is proposed by text similarity. The drafting
documents come with the data deposit as PDFs, in data/delphi/provenance/.
"Delphi panel v1.pdf" is the agent's first draft (35 shared, 15
policymaker-only and 15 scientist-only statements), and "Refined Delphi Panel
Questionnaire.pdf" holds the study team's intermediate version, before the
heading "Delphi Panel Questionnaire (Reduced to 30 Items)", and after it the 17
statements of Round 1. Their items were transcribed once from the Word
originals into v1_draft_items.csv (id, section, text) and
intermediate_items.csv (id, text), which this script reads.
Each Round 1 statement is paired with its closest v1 statement by cosine
similarity of stemmed content words weighted by rarity, so that a shared rare
word such as "privacy" counts for more than "model". A further v1 statement
joins as a source when it scores at least V1_ADD_FRAC of the best and adds at
least V1_ADD_WORDS Round 1 words the sources so far lack; two or more sources
make a merge. The classes are those of r4_round_comparison.classify_wording.

The same rule then chains the draft to Round 1 through the intermediate version,
v1 to the intermediate statements and those to Round 1, all three scored with
one rarity weighting, and reports where the chained v1 sources differ from the
direct ones. The chain uses the direct sources (study team, 4 November 2026);
the chained ones are a record only. Without the two item files this step is
skipped and the chain stops at Round 1.

Outputs:
  tables/revision_mapping.tex
  data/generated/provenance/v1_r1_mapping.csv       one row per Round 1 statement, direct
  data/generated/provenance/v1_r1_chained.csv       one row per Round 1 statement, direct
                                          against chained (record, not used)
  data/generated/provenance/provenance_chain.csv    one row per Round 4 statement
  tables/statement_provenance.tex   the chain as an SI table

Usage:
    python scripts/statement_provenance.py
"""
import argparse
import csv
import math
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from r4_statements import R4_TO_R3, SECTION_NAMES, ordered_ids  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PROVENANCE_DIR = PROJECT_ROOT / "data" / "delphi" / "provenance"
MAPPING_CSV = PROVENANCE_DIR / "r2_r3_mapping.csv"
DOCUMENTED_CSV = PROVENANCE_DIR / "r1_r2_documented.csv"
V1_ITEMS_CSV = PROVENANCE_DIR / "v1_draft_items.csv"
INTERMEDIATE_CSV = PROVENANCE_DIR / "intermediate_items.csv"
# The generated CSVs, kept apart from the deposited inputs.
OUTPUT_DIR = PROJECT_ROOT / "data" / "generated" / "provenance"
ROUND1_TABLE = PROVENANCE_DIR / "initial_statements.tex"
TABLE_OUT = PROJECT_ROOT / "tables" / "revision_mapping.tex"
PROVENANCE_OUT = PROJECT_ROOT / "tables" / "statement_provenance.tex"

V1_NEW_MAX = 0.2   # best cosine below this: the Round 1 statement has no v1 source
V1_STRONG = 0.35    # from here up a v1 proposal is labelled a strong overlap
V1_ADD_FRAC = 0.6   # a further v1 source scores at least this share of the best
V1_ADD_WORDS = 2    # and adds at least this many Round 1 stems not yet covered
V1_MAX_SOURCES = 4

# ── The revision-mapping table (tab:revision_mapping) ─────────────────────────
# Everything above the first section heading, as the hand-written table had it.
TABLE_HEAD = r"""% Auto-generated by scripts/statement_provenance.py -- do not edit by hand.
\begingroup\footnotesize
%% The note column is ragged, as every other paragraph column in the manuscript
%% is. Justified, it set 22 lines at a badness of 1000 and above, four at 10000.
\begin{longtable}{l l c l >{\raggedright\arraybackslash}p{0.4\textwidth}}
\caption{Summary of statement revisions from Round~2 (26 statements) to Round~3 (42 statements), by section and type of change. R2 and R3 numbers are sequential positions within each round, running across all sections, so they differ from the section-letter identifiers (such as R3-B07) used in Supplementary Note~\ref{sec:app:round_feedback}.}\label{tab:revision_mapping}\\
\toprule
\textbf{R2} & \textbf{R3} & \textbf{Sec.} & \textbf{Change} & \textbf{Summary} \\
\midrule
\endfirsthead
\caption[]{\emph{(continued)}}\\
\toprule
\textbf{R2} & \textbf{R3} & \textbf{Sec.} & \textbf{Change} & \textbf{Summary} \\
\midrule
\endhead
\midrule \multicolumn{5}{r}{\emph{continued on next page}}\\
\endfoot
\bottomrule
\endlastfoot
"""
TABLE_TAIL = "\\end{longtable}\n\\endgroup\n"


def read_mapping() -> list:
    with MAPPING_CSV.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def build_table(rows: list) -> str:
    """Rows are grouped under the section of their Round 2 statement. The first
    heading sits under \\midrule with a small gap, and later ones under \\hline."""
    lines = []
    for n, sec in enumerate(dict.fromkeys(r["r2_section"] for r in rows)):
        if n:
            lines.append(r"\hline")
        lines.append(rf"\multicolumn{{5}}{{l}}{{\textbf{{Section {sec}: {SECTION_NAMES[sec]}}}}} \\")
        if not n:
            lines.append(r"\addlinespace[2pt]")
        for r in rows:
            if r["r2_section"] == sec:
                lines.append(f"{r['r2']} & {r['r3']} & {r['r3_section']} & "
                             f"{r['change']} & {r['summary']} \\\\")
    return TABLE_HEAD + "\n".join(lines) + "\n" + TABLE_TAIL


# ── Identifiers ────────────────────────────────────────────────────────────────
def positions(cell: str) -> list:
    """'1, 2, 3' -> [1, 2, 3]; '6+17' -> [6, 17]; '---' -> []."""
    return [int(p) for p in re.findall(r"\d+", cell)]


def round3_ids(rows: list) -> dict:
    """{Round 3 position: section id such as 'B-3'}, from the table itself.

    Each section's positions are contiguous, so a position's id is its offset
    from the section's first position.
    """
    section_of = {}
    for r in rows:
        for p in positions(r["r3"]):
            if p in section_of:
                raise SystemExit(f"error: Round 3 position {p} appears twice in {MAPPING_CSV.name}")
            section_of[p] = r["r3_section"]
    if sorted(section_of) != list(range(1, len(section_of) + 1)):
        raise SystemExit(f"error: Round 3 positions in {MAPPING_CSV.name} are not 1..{len(section_of)}")
    first = {}
    for p in sorted(section_of):
        first.setdefault(section_of[p], p)
    return {p: f"{s}-{p - first[s] + 1}" for p, s in section_of.items()}


# ── Round 1 and Round 2 wording ────────────────────────────────────────────────
def round1_statements() -> dict:
    """{number: text} from the initial statements table."""
    src = ROUND1_TABLE.read_text(encoding="utf-8")
    out = {int(n): t for n, t in re.findall(r"^(\d+) & (.+?) \\\\\s*$", src, re.M)}
    if sorted(out) != list(range(1, 18)):
        raise SystemExit(f"error: expected Round 1 statements 1..17 in {ROUND1_TABLE.name}")
    return {n: latex_to_text(t) for n, t in out.items()}


def latex_to_text(s: str) -> str:
    for a, b in [("``", '"'), ("''", '"'), ("~", " "), (r"\%", "%"), (r"\&", "&")]:
        s = s.replace(a, b)
    return s


STOP = set("""a an and are as at be by can for from in into is it its of on or should
that the their them these this to with within when where which while will""".split())


def read_documented() -> dict:
    """{Round 2 position: ([Round 1 sources], how the link is known)} from the
    feedback summaries. "wording" where the Round 2 statement continues a Round 1
    statement, "Round 1 feedback" where it was written new from the feedback, and
    "not recorded" where the documents give neither."""
    with DOCUMENTED_CSV.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    if sorted(int(r["r2_position"]) for r in rows) != list(range(1, 27)):
        raise SystemExit(f"error: expected Round 2 positions 1..26 in {DOCUMENTED_CSV.name}")
    out = {}
    for r in rows:
        sources = positions(r["r1_source"])
        if sources:
            known = "wording"
        elif "Round 1" in r["basis"] and "feedback" in r["basis"]:
            known = "Round 1 feedback"
        else:
            known = "not recorded"
        out[int(r["r2_position"])] = (sources, known)
    return out


# ── GPT-5 first draft -> Round 1 ───────────────────────────────────────────────
V1_FIELDS = ("id", "section", "text")
INTERMEDIATE_FIELDS = ("id", "text")


def read_items(path: Path, fields: tuple) -> list:
    """The rows of an item file, as dicts with the given fields."""
    with path.open(encoding="utf-8", newline="") as fh:
        return [{k: row[k] for k in fields} for row in csv.DictReader(fh)]


STEM_SUFFIXES = ("ations", "ation", "ings", "ing", "ed", "es", "e", "s", "ly")


def stems(text: str) -> set:
    """Content-word stems: stop words dropped and a few English endings cut, so
    that "updated" meets "updates" and "emergencies" meets "emergency"."""
    out = set()
    for w in re.findall(r"[a-z]+", text.lower()):
        if w in STOP or len(w) < 3:
            continue
        if w.endswith("ies") and len(w) > 5:
            w = w[:-3] + "y"
        else:
            for suf in STEM_SUFFIXES:
                if w.endswith(suf) and len(w) - len(suf) >= 4:
                    w = w[:-len(suf)]
                    break
        out.add(w)
    return out


def rarity_cosine(docs: list):
    """Cosine similarity of stem sets, each stem weighted by its rarity across docs."""
    df = {}
    for d in docs:
        for w in d:
            df[w] = df.get(w, 0) + 1
    idf = {w: math.log(len(docs) / k) + 1 for w, k in df.items()}

    def cosine(a, b):
        den = math.sqrt(sum(idf[w] ** 2 for w in a)) * math.sqrt(sum(idf[w] ** 2 for w in b))
        return sum(idf[w] ** 2 for w in a & b) / den if den else 0.0
    return cosine


def pick_sources(s: set, candidates: list, cosine) -> tuple:
    """The closest candidate, and any further one that scores at least
    V1_ADD_FRAC of the best and adds V1_ADD_WORDS stems the others lack.
    Returns (source indices, the ranking)."""
    ranked = sorted(((cosine(s, v), i) for i, v in enumerate(candidates)), key=lambda x: (-x[0], x[1]))
    best, top = ranked[0]
    sources = []
    if best >= V1_NEW_MAX:
        sources, covered = [top], s & candidates[top]
        for score, i in ranked[1:]:
            if len(sources) == V1_MAX_SOURCES or score < V1_ADD_FRAC * best:
                break
            if len((s & candidates[i]) - covered) >= V1_ADD_WORDS:
                sources.append(i)
                covered |= s & candidates[i]
    return sources, ranked


def map_v1_round1(v1: list, r1: dict) -> list:
    """Proposed v1 source(s) for each Round 1 statement, with its wording class."""
    from r4_round_comparison import classify_wording
    v_stems = [stems(s["text"]) for s in v1]
    r_stems = {n: stems(t) for n, t in r1.items()}
    cosine = rarity_cosine(v_stems + list(r_stems.values()))

    rows = []
    for n, text in r1.items():
        s = r_stems[n]
        sources, ranked = pick_sources(s, v_stems, cosine)
        best = ranked[0][0]
        if sources:
            klass, similarity = classify_wording(" ".join(v1[i]["text"] for i in sources),
                                                 text, len(sources))
        else:
            klass, similarity = "new", ""
        nxt = next((sc, i) for sc, i in ranked if i not in sources)
        rows.append({
            "r1": n,
            "wording_class": klass,
            "v1_sources": "+".join(v1[i]["id"] for i in sources),
            "scores": "+".join(f"{cosine(s, v_stems[i]):.2f}" for i in sources),
            "word_similarity": similarity,
            "next_candidate": f"{v1[nxt[1]]['id']} ({nxt[0]:.2f})",
            "status": ("proposal (strong overlap), to be confirmed by the authors"
                       if best >= V1_STRONG else
                       "proposal (weak overlap), to be confirmed by the authors"
                       if sources else "no v1 source, to be confirmed by the authors"),
            "r1_text": text,
            "v1_text": " | ".join(v1[i]["text"] for i in sources),
        })
    return rows


def chain_v1_round1(v1: list, inter: list, r1: dict, direct: list) -> list:
    """Each Round 1 statement's v1 sources through the intermediate version,
    against its direct ones, with the score of the direct match and of both
    steps (Round 1 to its closest intermediate statement, and that statement to
    its closest v1). All three use one rarity weighting, over v1, intermediate
    and Round 1. A record only: the chain keeps the direct sources."""
    v_stems = [stems(s["text"]) for s in v1]
    i_stems = [stems(s["text"]) for s in inter]
    r_stems = {n: stems(t) for n, t in r1.items()}
    cosine = rarity_cosine(v_stems + i_stems + list(r_stems.values()))
    v_index = {s["id"]: k for k, s in enumerate(v1)}
    inter_v1 = [pick_sources(s, v_stems, cosine) for s in i_stems]
    rows = []
    for d in direct:
        n, s = d["r1"], r_stems[d["r1"]]
        direct_ids = d["v1_sources"].split("+") if d["v1_sources"] else []
        direct_score = max((cosine(s, v_stems[v_index[v]]) for v in direct_ids), default=0.0)
        mids, ranked = pick_sources(s, i_stems, cosine)
        chained = sorted({v1[i]["id"] for m in mids for i in inter_v1[m][0]}, key=v_index.get)
        step2 = ranked[0][0] if mids else 0.0
        step1 = inter_v1[mids[0]][1][0][0] if mids and inter_v1[mids[0]][0] else 0.0
        agree = set(chained) == set(direct_ids)
        rows.append({
            "r1": n,
            "direct_v1": "+".join(direct_ids),
            "direct_score": f"{direct_score:.2f}",
            "intermediate": "+".join(inter[m]["id"] for m in mids),
            "step_r1_to_intermediate": f"{step2:.2f}",
            "step_intermediate_to_v1": f"{step1:.2f}",
            "chained_v1": "+".join(chained),
            "agree": "yes" if agree else "no",
            "intermediate_text": " | ".join(inter[m]["text"] for m in mids),
        })
    return rows


# ── Chain ──────────────────────────────────────────────────────────────────────
def chain(rows: list, documented: dict, v1_of: dict = None) -> list:
    """One row per Round 4 statement, back to Round 1 and, where the drafting
    documents are present (v1_of), to the GPT-5 first draft. The origin is the
    earliest round any of the statement's sources reaches."""
    r3_id = round3_ids(rows)
    pos_of = {v: k for k, v in r3_id.items()}
    origin = {}
    for r in rows:
        for p in positions(r["r3"]):
            origin[p] = (positions(r["r2"]), r["change"])
    out = []
    for sid in ordered_ids():
        r3_ids = R4_TO_R3[sid]
        r3_pos = [pos_of[i] for i in r3_ids]
        r2_pos = sorted({q for p in r3_pos for q in origin[p][0]})
        changes = sorted({origin[p][1] for p in r3_pos})
        r1 = sorted({n for q in r2_pos for n in documented[q][0]})
        known = "; ".join(dict.fromkeys(documented[q][1] for q in r2_pos))
        v1 = sorted({v for n in r1 for v in (v1_of or {}).get(n, [])})
        if v1:
            source = "v1 draft"
        elif r1:
            source = "Round 1, not in the v1 draft" if v1_of is not None else "Round 1"
        else:
            source = "added in Round 2" if r2_pos else "added in Round 3"
        out.append({
            "r4": sid,
            "r3": "+".join(r3_ids),
            "r3_positions": "+".join(map(str, r3_pos)),
            "r2_to_r3_change": "; ".join(changes),
            "r2_positions": "+".join(map(str, r2_pos)) or "new in Round 3",
            "r1": "+".join(map(str, r1)) if r2_pos else "",
            "r1_link": known,
            "v1_proposed": "+".join(v1),
            "origin": source,
        })
    return out


def build_provenance_table(links: list) -> str:
    """One row per Round 4 statement, back through Rounds 3, 2 and 1 to the
    agent's draft (v1), with its origin and how the Round 1 to Round 2 link is
    known. The v1 column holds matches by text similarity, and the caption
    says so."""
    def cell(v):
        return v.replace("v1-", "") if v else "--"
    rows = []
    for section in "ABCD":
        rows.append(rf"\multicolumn{{7}}{{@{{}}l}}{{\textbf{{Section {section}: {SECTION_NAMES[section]}}}}} \\")
        for c in links:
            if c["r4"].startswith(section):
                r2 = "--" if c["r2_positions"] == "new in Round 3" else c["r2_positions"]
                rows.append(f"{c['r4']} & {c['r3']} & {r2} & {cell(c['r1'])} & {cell(c['r1_link'])} & "
                            f"{cell(c['v1_proposed'])} & {c['origin']} \\\\")
        rows.append(r"\addlinespace[3pt]")
    head = (r"\textbf{R4} & \textbf{R3} & \textbf{R2} & \textbf{R1} & \textbf{R1 link} & "
            r"\textbf{v1} & \textbf{Origin} \\")
    return (
        "% Auto-generated by scripts/statement_provenance.py -- do not edit by hand.\n"
        "\\begingroup\\footnotesize\\setlength{\\tabcolsep}{4pt}\n"
        "\\begin{longtable}{@{}l l l l >{\\raggedright\\arraybackslash}p{8.2em} l l@{}}\n"
        "\\caption{\\textbf{Provenance of the 40 consensus statements.} Each row traces a statement "
        "from its Round~4 number (R4) back through its Round~3, Round~2, and Round~1 numbers to the "
        "items of the agent's first draft (v1) from which it descends. \\textit{R1 link} gives how "
        "the Round~2 statement arose: reworded from a Round~1 statement (\\textit{wording}) or added "
        "in response to Round~1 feedback. By origin, 23 statements descend from the draft, 11 were "
        "added in Round~2, and 6 in Round~3. Links from Round~1 to Round~4 follow the study team's "
        "revision mapping for each round. Links from the draft to Round~1 come from comparing the "
        "texts, because no mapping was recorded for that step. A plus sign joins items that were "
        "merged, and a dash marks a round before the statement existed. The trace ends at the draft, "
        "because the agent's output does not record which extracted review items each draft item "
        "drew on (Methods).}\\label{tab:statement_provenance}\\\\\n"
        f"\\toprule\n{head}\n\\midrule\n\\endfirsthead\n"
        f"\\caption[]{{\\emph{{(continued)}}}}\\\\\n\\toprule\n{head}\n\\midrule\n\\endhead\n"
        "\\midrule \\multicolumn{7}{r}{\\emph{continued on next page}}\\\\\n\\endfoot\n"
        "\\bottomrule\n\\endlastfoot\n"
        + "\n".join(rows) + "\n\\end{longtable}\n\\endgroup\n"
    )


def write_csv(path: Path, rows: list) -> None:
    with path.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.parse_args()
    for d in (OUTPUT_DIR, TABLE_OUT.parent, PROVENANCE_OUT.parent):
        d.mkdir(parents=True, exist_ok=True)
    rows = read_mapping()
    TABLE_OUT.write_text(build_table(rows), encoding="utf-8")
    print(f"wrote {TABLE_OUT}")

    r1 = round1_statements()
    documented = read_documented()
    linked = sum(1 for sources, _ in documented.values() if sources)
    print(f"read {DOCUMENTED_CSV.name}: {linked} of {len(documented)} Round 2 statements "
          f"continue a Round 1 statement")

    v1_of = None
    if V1_ITEMS_CSV.exists() and INTERMEDIATE_CSV.exists():
        v1 = read_items(V1_ITEMS_CSV, V1_FIELDS)
        by_section = {s: sum(1 for x in v1 if x["section"] == s) for s in "ABC"}
        print(f"v1 draft: {len(v1)} statements {by_section}, from {V1_ITEMS_CSV.name}")
        mapping = map_v1_round1(v1, r1)
        write_csv(OUTPUT_DIR / "v1_r1_mapping.csv", mapping)
        direct_classes = {}
        for m in mapping:
            direct_classes[m["wording_class"]] = direct_classes.get(m["wording_class"], 0) + 1
        print(f"wrote {OUTPUT_DIR / 'v1_r1_mapping.csv'}: {direct_classes} (direct)")
        inter = read_items(INTERMEDIATE_CSV, INTERMEDIATE_FIELDS)
        chained = chain_v1_round1(v1, inter, r1, mapping)
        write_csv(OUTPUT_DIR / "v1_r1_chained.csv", chained)
        print(f"intermediate version: {len(inter)} statements, from {INTERMEDIATE_CSV.name}")
        print("  R1  direct (score)             via intermediate (R1-int, int-v1)       chained             agree")
        for c in chained:
            print(f"  {c['r1']:>2}  {c['direct_v1'] or '-':22s} ({c['direct_score']})  "
                  f"{c['intermediate'] or '-':14s} ({c['step_r1_to_intermediate']}, "
                  f"{c['step_intermediate_to_v1']})  {c['chained_v1'] or '-':22s} {c['agree']}")
        print(f"wrote {OUTPUT_DIR / 'v1_r1_chained.csv'} (record only; the chain uses the direct sources)")
        v1_of = {m["r1"]: m["v1_sources"].split("+") if m["v1_sources"] else [] for m in mapping}
        reached = {v for vs in v1_of.values() for v in vs}
        print(f"{len(reached)} of {len(v1)} v1 statements reach Round 1 (proposal)")
    else:
        print(f"{V1_ITEMS_CSV.name} or {INTERMEDIATE_CSV.name} not in data/delphi/provenance/; "
              "the chain stops at Round 1")

    links = chain(rows, documented, v1_of)
    write_csv(OUTPUT_DIR / "provenance_chain.csv", links)
    PROVENANCE_OUT.write_text(build_provenance_table(links), encoding="utf-8")
    print(f"wrote {PROVENANCE_OUT}")
    origins = {}
    for c in links:
        origins[c["origin"]] = origins.get(c["origin"], 0) + 1
    print(f"wrote {OUTPUT_DIR / 'provenance_chain.csv'}: {len(links)} Round 4 statements "
          f"by origin {origins}")


if __name__ == "__main__":
    main()
